def generate_expert_questions(templates, num_questions):
    """生成专业级易经大师咨询问题"""
    questions = []
    
    # 合并所有词汇库
    all_term_banks = {**professional_terms, **reality_terms, **domain_terms, **historical_terms}
    
    for _ in range(num_questions):
        template = random.choice(templates)
        question = template
        
        # 替换所有占位符
        for placeholder, options in all_term_banks.items():
            if placeholder in question:
                # 确保同一个占位符在同一个问题中不使用重复值
                used_values = set()
                while placeholder in question:
                    available_options = [opt for opt in options if opt not in used_values]
                    if not available_options:
                        break
                    choice = random.choice(available_options)
                    used_values.add(choice)
                    question = question.replace(placeholder, choice, 1)
        
        questions.append(question)
    
    return questions

