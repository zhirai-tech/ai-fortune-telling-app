def save_training_data(questions, responses, filename):
    """保存训练数据"""
    # 确保目录存在
    os.makedirs(os.path.dirname(filename), exist_ok=True)

    with open(filename, 'w', encoding='utf-8') as f:
        for i, (question, response) in enumerate(zip(questions, responses)):
            f.write(f"### 问题 {i+1}:\n")
            f.write(f"用户: {question}\n")
            f.write(f"大师: {response}\n\n")
            
            # 添加一些深度追问和回答
            if i % 3 == 0:  # 每3个问题添加一次追问
                followup = generate_deep_followups(1)[0]
                followup_response = generate_master_responses(1)[0]
                f.write(f"追问: {followup}\n")
                f.write(f"大师: {followup_response}\n\n")

